import fs from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { mergeGeometries } from 'three/addons/utils/BufferGeometryUtils.js';
const input='public/annienexus/brain-hra.glb';
const raw=await fs.readFile(input);
const gltf=await new GLTFLoader().parseAsync(raw.buffer.slice(raw.byteOffset,raw.byteOffset+raw.byteLength),'');
gltf.scene.updateMatrixWorld(true);
const parts=[];
gltf.scene.traverse(mesh=>{
 if(!mesh.isMesh)return;
 const geometry=mesh.geometry.clone().applyMatrix4(mesh.matrixWorld);
 for(const name of Object.keys(geometry.attributes))if(name!=='position'&&name!=='normal')geometry.deleteAttribute(name);
 if(!geometry.index)geometry.setIndex(Array.from({length:geometry.attributes.position.count},(_,i)=>i));
 parts.push(geometry);
});
const geometry=mergeGeometries(parts);
if(!geometry)throw new Error('Cannot merge model');
geometry.computeBoundingBox();
const center=geometry.boundingBox.getCenter(new THREE.Vector3());
const size=geometry.boundingBox.getSize(new THREE.Vector3());
const scale=3.65/Math.max(size.x,size.y,size.z);
geometry.translate(-center.x,-center.y,-center.z).scale(scale,scale,scale);
const position=new Float32Array(geometry.attributes.position.array);
const normal=new Float32Array(geometry.attributes.normal.array);
const index=new Uint32Array(geometry.index.array);
const header=Buffer.alloc(16);header.write('ANB1');header.writeUInt32LE(position.length/3,4);header.writeUInt32LE(index.length,8);
const packed=Buffer.concat([header,Buffer.from(position.buffer),Buffer.from(normal.buffer),Buffer.from(index.buffer)]);
const zipped=gzipSync(packed,{level:9});
const target='public/annienexus/brain-surface.bin.gz';await fs.writeFile(target,zipped);
const sha=b=>createHash('sha256').update(b).digest('hex');
const report={source:input,sourceSha256:sha(raw),derived:target,derivedSha256:sha(zipped),vertices:position.length/3,triangles:index.length/3,originalBytes:raw.length,derivedBytes:zipped.length,uncompressedBytes:packed.length,reductionPercent:+((1-zipped.length/raw.length)*100).toFixed(1),method:'Lossless gzip; same indexed triangles, positions and normals; world transforms merged and normalized as in the original viewer. No decimation or quantization.',generator:'scripts/optimize-brain.mjs'};
await fs.writeFile('docs/annienexus/brain-optimization.json',JSON.stringify(report,null,2)+'\n');console.log(report);
